"""Independent test encoder. pip install qrcode pillow pillow-heif"""
import base64
import io
import json
from pathlib import Path
import qrcode
from PIL import Image, ImageFilter, ImageOps
import pillow_heif

pillow_heif.register_heif_opener()
fixtures = {}

def qr(text='99chat-fixture-A', side=300):
    code = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_H, box_size=8, border=4)
    code.add_data(text)
    code.make(fit=True)
    return code.make_image().convert('RGB').resize((side, side), Image.Resampling.NEAREST)

def add(name, img, expected=('99chat-fixture-A',), fmt='PNG', **kwargs):
    out = io.BytesIO()
    img.save(out, format=fmt, **kwargs)
    fixtures[name] = {'data': base64.b64encode(out.getvalue()).decode(), 'expected': list(expected),
                      'width': img.width, 'height': img.height}

for side in [100, 300, 1000]: add(f'size-{side}', qr(side=side))
for angle in [90, 180, 270]: add(f'rotate-{angle}', qr().rotate(angle, expand=True))
add('jpg', qr(), fmt='JPEG', quality=92)
add('webp', qr(), fmt='WEBP', lossless=True)
add('heic', qr(), fmt='HEIF', quality=95)
for orientation in range(2, 9):
    canvas = Image.new('RGB', (450, 350), 'white'); canvas.paste(qr(side=200), (180, 100))
    exif = Image.Exif(); exif[274] = orientation
    add(f'exif-{orientation}', canvas, fmt='JPEG', quality=95, exif=exif)
    fixtures[f'exif-{orientation}']['center'] = {
        2:[170,200], 3:[170,150], 4:[280,150], 5:[200,280],
        6:[150,280], 7:[150,170], 8:[200,170]}[orientation]
add('blur', qr().filter(ImageFilter.GaussianBlur(.7)))
add('low-contrast', ImageOps.colorize(qr().convert('L'), '#989898', '#c0c0c0'))
add('color', ImageOps.colorize(qr().convert('L'), '#164f9d', '#fff0c8'))
add('inverted', ImageOps.invert(qr()))
transparent = qr().convert('RGBA')
transparent.putdata([(r,g,b,0 if r == 255 else 255) for r,g,b,a in transparent.getdata()])
add('transparent', transparent)
occluded = qr(); occluded.paste('white', (140,140,157,157)); add('occluded-small', occluded)
occluded = qr(); occluded.paste('white', (0,0,180,300)); add('occluded-severe', occluded, ())
tilt = qr().transform((300,300), Image.Transform.PERSPECTIVE,
    (1, .06, -8, .025, 1, -5, .0002, -.00015), Image.Resampling.BICUBIC, fillcolor='white')
add('perspective', tilt)
for name, size, pos in [('4k-corner',(3840,2160),(3700,2020)),
                        ('4k-edge',(3840,2160),(0,900)),
                        ('4k-center',(3840,2160),(1850,1000)),
                        ('long',(1080,12000),(850,11100))]:
    canvas=Image.new('RGB',size,'#f5f5f5'); canvas.paste(qr(side=100),pos); add(name,canvas)
canvas=Image.new('RGB',(1000,700),'white')
canvas.paste(qr(side=200),(10,10)); canvas.paste(qr('99chat-fixture-B',300),(680,350))
add('multiple',canvas,('99chat-fixture-A','99chat-fixture-B'))
mixed=Image.new('RGB',(1000,700),'#aaaaaa')
mixed.paste(qr(side=200),(10,10)); mixed.paste(ImageOps.invert(qr('99chat-fixture-B',300)),(680,350))
add('mixed-polarity',mixed,('99chat-fixture-A','99chat-fixture-B'))
